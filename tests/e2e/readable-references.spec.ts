import { test,expect } from '@playwright/test';
import { apiDraft,signInLocal } from './helpers';
test('source references quote original evidence and clause links highlight their destination',async({page,request})=>{
 const data=await apiDraft(request);
 await signInLocal(page);
 await page.getByLabel('Existing project',{exact:true}).selectOption(data.project.id);
 await page.getByLabel('Existing run',{exact:true}).selectOption(data.run.id);
 await page.getByRole('button',{name:'Open run',exact:true}).click();
 const article=page.getByRole('article',{name:'Readable draft'});
 await article.getByText('Source references',{exact:true}).first().click();
 await expect(article.getByRole('blockquote').first()).toContainText(data.source.text);
 const link=article.getByRole('link',{name:/Story 1:/}).first();
 await page.locator('#preview-stories').evaluate((node:HTMLDetailsElement)=>node.open=false);
 await link.click();
 await expect(page.locator('.reference-highlight')).toContainText('As a reviewer');
 await expect(page.locator('.reference-highlight')).toBeFocused();
 await expect(article.getByRole('link',{name:/Requirement 1:/}).first()).toBeVisible();
});
