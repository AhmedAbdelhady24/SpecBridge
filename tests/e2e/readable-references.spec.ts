test('whole-statement evidence changes and new requirements retain readable citations in diffs',async({page,request})=>{
 const data=await apiDraft(request);
 const other=await data.send(`/projects/${data.project.id}/sources`,{text:'Second evidence: an additional scope decision.'});
 const headers={Authorization:`Bearer ${process.env.SPECBRIDGE_TOKEN!}`};
 const previous=await(await request.get(`${process.env.SPECBRIDGE_E2E_API_ORIGIN || 'http://127.0.0.1:8000'}/api/projects/${data.project.id}/revisions/${data.run.revision_id}`,{headers})).json();
 const next=structuredClone(previous.artifact);next.scope[0].source_ids=[other.id];
 const id=`REQ-${crypto.randomUUID()}`;
 next.requirements.push({...next.requirements[0],id,text:'Additional source-linked requirement',source_ids:[other.id]});
 next.stories.push({...next.stories[0],id:`STORY-${crypto.randomUUID()}`,requirement_ids:[id],source_ids:[other.id]});
 await data.send(`/projects/${data.project.id}/revisions/${previous.id}/edits`,{expected_digest:previous.digest,artifact:next});
 await signInLocal(page);
 await page.getByLabel('Existing project',{exact:true}).selectOption(data.project.id);
 await page.getByLabel('Existing run',{exact:true}).selectOption(data.run.id);
 await page.getByRole('button',{name:'Open run',exact:true}).click();
 await page.getByRole('button',{name:'Changes',exact:true}).click();
 await page.getByRole('button',{name:'Compare revisions',exact:true}).click();
 await expect(page.getByRole('navigation',{name:'Changed sections'})).toBeVisible();
 for(const reference of await page.locator('.document-diff').getByText('Source references',{exact:true}).all())await reference.click();
 await expect(page.locator('.diff-file[id$="-scope"]')).toContainText(data.source.text);
 await expect(page.locator('.diff-file[id$="-scope"]')).toContainText(other.text);
 await expect(page.locator('.diff-file[id$="-requirements"]')).toContainText(other.text);
});
