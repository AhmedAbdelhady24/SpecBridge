test('a delayed context selection cannot cross into another project', async ({ page, request }) => {
  const create = async (name: string) => (await request.post(`${api}/projects`, { headers: authHeaders(), data: { name } })).json();
  const first = await create(`Context race A ${Date.now()}`);
  const second = await create(`Context race B ${Date.now()}`);
  await request.post(`${api}/projects/${first.id}/knowledge`, { headers: authHeaders(), data: { entity_type: 'goal', title: 'Private context A', text: 'A-only assumption.', kind: 'assumption', source_ids: [], archived: false } });
  await signInLocal(page);
  await page.getByLabel('Existing project', { exact: true }).selectOption(first.id);
  await page.getByText('Project context', { exact: true }).click();
  await page.getByLabel('Context search', { exact: true }).fill('Private context A');
  await page.getByRole('button', { name: 'Search context', exact: true }).click();
  let release!: () => void;
  const held = new Promise<void>(resolve => { release = resolve; });
  let started!: () => void;
  const captured = new Promise<void>(resolve => { started = resolve; });
  await page.route('**/knowledge/*/sources', async route => {
    const response = await route.fetch();
    started();
    await held;
    await route.fulfill({ response });
  });
  await page.getByRole('button', { name: 'Select context: Private context A', exact: true }).click();
  await captured;
  await page.getByLabel('Existing project', { exact: true }).selectOption(second.id);
  const returned = page.waitForResponse(r => r.url().includes('/knowledge/') && r.url().endsWith('/sources'));
  release();
  await returned;
  await page.getByLabel('Feature idea', { exact: true }).fill('B-only request.');
  if(!await page.getByLabel('I acknowledge generation uses this destination',{exact:true}).isVisible())await page.getByRole('button',{name:'Review generation',exact:true}).click();
  await page.getByLabel('I acknowledge generation uses this destination', { exact: true }).check();
  const sent = page.waitForRequest(r => r.url().endsWith(`/projects/${second.id}/runs`) && r.method() === 'POST');
  await page.getByRole('button', { name: 'Generate draft', exact: true }).click();
  expect((await sent).postDataJSON().source_ids).toHaveLength(1);
  await editDraft(page);
  await expect(page.getByLabel('Title', { exact: true })).toHaveValue(/DEMO fixture/);
});

test('verification cannot apply to unsaved displayed content', async ({ page, request }) => {
  const project = await (await request.post(`${api}/projects`, { headers: authHeaders(), data: { name: `Saved verification ${Date.now()}` } })).json();
  const source = await (await request.post(`${api}/projects/${project.id}/sources`, { headers: authHeaders(), data: { text: 'Source evidence for a scope decision.' } })).json();
  const entry = await (await request.post(`${api}/projects/${project.id}/knowledge`, { headers: authHeaders(), data: { entity_type: 'decision', title: 'Saved claim', text: 'Claim A is saved.', kind: 'user_provided', source_ids: [source.id], archived: false } })).json();
  await signInLocal(page);
  await page.getByLabel('Existing project', { exact: true }).selectOption(project.id);
  await page.getByText('Project context', { exact: true }).click();
  await page.getByRole('button', { name: 'Edit Saved claim', exact: true }).click();
  await page.getByLabel('Verification note', { exact: true }).fill('Reviewing the displayed claim.');
  await page.getByLabel('I confirm this knowledge against the cited original evidence', { exact: true }).check();
  await expect(page.getByRole('button', { name: 'Record human verification', exact: true })).toBeEnabled();
  await page.getByLabel('Background text', { exact: true }).fill('Claim B is an unsaved edit.');
  await expect(page.getByRole('button', { name: 'Record human verification', exact: true })).toBeDisabled();
  await expect(page.getByLabel('I confirm this knowledge against the cited original evidence', { exact: true })).not.toBeChecked();
  let history = await (await request.get(`${api}/projects/${project.id}/knowledge/${entry.id}/history`, { headers: authHeaders() })).json();
  expect(history).toHaveLength(1);
  expect(history[0].text).toBe('Claim A is saved.');
  await page.getByRole('button', { name: 'Save background', exact: true }).click();
  await page.getByLabel('Verification note', { exact: true }).fill('Reviewing saved claim B.');
  await page.getByLabel('I confirm this knowledge against the cited original evidence', { exact: true }).check();
  await page.getByRole('button', { name: 'Record human verification', exact: true }).click();
  await expect(page.getByText('Current classification: Marked verified', { exact: true })).toBeVisible();
  history = await (await request.get(`${api}/projects/${project.id}/knowledge/${entry.id}/history`, { headers: authHeaders() })).json();
  expect(history[0].text).toBe('Claim B is an unsaved edit.');
  expect(history[0].kind).toBe('verified');
});

test('all knowledge records, versions and artifact revisions remain reachable after twenty', async ({ page, request }) => {
  const send = async (path: string, data: unknown) => {
    const response = await request.post(`${api}${path}`, { headers: authHeaders(), data });
    expect(response.ok()).toBeTruthy();
    return response.json();
  };
  const project = await send('/projects', { name: `Paged knowledge ${Date.now()}` });
  const base = `/projects/${project.id}`;
  const entryBody = { entity_type: 'goal', text: 'Original version one.', kind: 'assumption', source_ids: [], archived: false };
  for (let i = 0; i < 21; i++) await send(`${base}/knowledge`, { ...entryBody, title: `Paged record ${i}` });
  const records = await (await request.get(`${api}${base}/knowledge?limit=50`, { headers: authHeaders() })).json();
  let entry = records[0];
  for (let version = 2; version <= 21; version++) entry = await send(`${base}/knowledge/${entry.id}/edits`, { expected_digest: entry.digest, entry: { ...entryBody, title: entry.title, text: `Changed version ${version}.` } });
  const source = await send(`${base}/sources`, { text: 'A feature with persistent revision history.' });
  let run = await send(`${base}/runs`, { source_ids: [source.id], skill_id: 'feature-handoff', intent: 'PRD', acknowledged_destination: 'fixture' });
  for (let stage = 0; stage < 6; stage++) run = await send(`${base}/runs/${run.id}/advance`, {});
  let revision = await (await request.get(`${api}${base}/revisions/${run.revision_id}`, { headers: authHeaders() })).json();
  for (let version = 2; version <= 21; version++) revision = await send(`${base}/revisions/${revision.id}/edits`, { expected_digest: revision.digest, artifact: { ...revision.artifact, title: `Paged revision ${version}` } });
  await signInLocal(page);
  await page.getByLabel('Existing project', { exact: true }).selectOption(project.id);
  await page.getByText('Project context', { exact: true }).click();
  const editButtons = page.getByRole('button', { name: /^Edit Paged record / });
  await expect(editButtons).toHaveCount(20);
  // Unsubmitted search text must not change the cursor's current result set.
  await page.getByLabel('Context search', { exact: true }).fill('no matching records');
  await page.getByRole('button', { name: 'Load more records', exact: true }).click();
  await expect(editButtons).toHaveCount(21);
  await expect(page.getByRole('button', { name: `Edit ${records[20].title}`, exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: 'Search context', exact: true }).click();
  await expect(editButtons).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Load more records', exact: true })).toHaveCount(0);
  await page.getByLabel('Context search', { exact: true }).fill('');
  await page.getByRole('button', { name: 'Search context', exact: true }).click();
  await expect(editButtons).toHaveCount(20);
  await page.getByRole('button', { name: `History ${entry.title}`, exact: true }).click();
  const history = page.getByRole('region', { name: 'Knowledge version history' });
  await expect(history.getByRole('heading', { name: 'Version 1 · Assumption', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Load older knowledge versions', exact: true }).click();
  await expect(history.getByRole('heading', { name: /^Version \d+ ·/ })).toHaveCount(21);
  await expect(history.getByRole('heading', { name: 'Version 1 · Assumption', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Load artifact history', exact: true }).click();
  await expect(page.getByRole('button', { name: /^View revision / })).toHaveCount(20);
  await page.getByRole('button', { name: 'Load older artifact revisions', exact: true }).click();
  await expect(page.getByRole('button', { name: /^View revision / })).toHaveCount(21);
  await page.getByRole('button', { name: /^View revision 1:/ }).click();
  await expect(page.getByRole('heading', { name: 'Saved revision 1', exact: true })).toBeVisible();
});
